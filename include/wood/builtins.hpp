inline const Builtin* find_builtin(std::string_view name) {
    for (const auto& builtin : builtins)
        if (builtin.name == name)
            return &builtin;
    return nullptr;
}
inline bool reserved_builtin(std::string_view name) {
    const auto* builtin = find_builtin(name);
    return builtin && builtin->reserved;
}
